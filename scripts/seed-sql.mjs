// Generates supabase/seed.sql from src/data/catalog.json.
// Usage: node scripts/seed-sql.mjs
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const { collections, categories, products } = JSON.parse(fs.readFileSync(path.join(root, "src/data/catalog.json"), "utf8"));

const q = (v) => (v === null || v === undefined ? "null" : `'${String(v).replace(/'/g, "''")}'`);
const arr = (a) => `array[${a.map(q).join(",")}]::text[]`;
const lines = ["-- Generated by scripts/seed-sql.mjs — initial catalog from the WordPress store.", "begin;"];

for (const c of collections) {
  lines.push(
    `insert into public.collections (slug, name, tagline, issue, cover) values (${q(c.slug)}, ${q(c.name)}, ${q(c.tagline)}, ${c.issue}, ${q(c.cover)}) on conflict (slug) do nothing;`,
  );
}
categories.forEach((c, i) => {
  lines.push(`insert into public.categories (slug, name, sort) values (${q(c.slug)}, ${q(c.name)}, ${i}) on conflict (slug) do nothing;`);
});
for (const p of products) {
  if (!p.variants.length) p.variants = [{ sku: null, size: null, color: null, price: p.price, stock: null, image: null }];
  lines.push(
    `insert into public.products (slug, name, description, price, collection_slug, categories, is_new, featured, images, created_at) values (${q(p.slug)}, ${q(p.name)}, ${q(p.description)}, ${p.price}, ${q(p.collection)}, ${arr(p.categories)}, ${p.is_new}, ${p.featured}, ${q(JSON.stringify(p.images))}::jsonb, ${q(p.created_at)}) on conflict (slug) do nothing;`,
  );
  p.variants.forEach((v, i) => {
    lines.push(
      `insert into public.variants (product_id, sku, size, color, price, stock, image, sort) select id, ${q(v.sku)}, ${q(v.size)}, ${q(v.color)}, ${v.price}, ${v.stock ?? "null"}, ${q(v.image)}, ${i} from public.products where slug = ${q(p.slug)} and not exists (select 1 from public.variants x join public.products y on y.id = x.product_id where y.slug = ${q(p.slug)} and x.size is not distinct from ${q(v.size)} and x.color is not distinct from ${q(v.color)});`,
    );
  });
}
lines.push("commit;");
fs.writeFileSync(path.join(root, "supabase/seed.sql"), lines.join("\n") + "\n");
console.log(`seed.sql: ${products.length} products, ${products.reduce((n, p) => n + p.variants.length, 0)} variants`);
